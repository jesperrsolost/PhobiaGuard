package com.example.phobiaguard


import android.app.NotificationManager
import android.content.Context
import android.content.Intent
import androidx.test.core.app.ApplicationProvider
import androidx.test.rule.GrantPermissionRule
import org.junit.Rule
import org.junit.Test
import org.junit.Assert.*
import org.junit.Before

class ScreenMonitoringServiceTest{
    @get:Rule
    val grantPermissionRule: GrantPermissionRule = GrantPermissionRule.grant(
        android.Manifest.permission.FOREGROUND_SERVICE_MEDIA_PROJECTION,
        android.Manifest.permission.FOREGROUND_SERVICE
    )
    @Before
    fun setUp() {
        val context = ApplicationProvider.getApplicationContext<Context>()
        val instrumentation = androidx.test.platform.app.InstrumentationRegistry.getInstrumentation()

        // Grant notification permission
        instrumentation.uiAutomation.executeShellCommand(
            "pm grant ${context.packageName} android.permission.POST_NOTIFICATIONS"
        )

        instrumentation.uiAutomation.executeShellCommand(
            "pm grant ${context.packageName} android.permission.FOREGROUND_SERVICE_MEDIA_PROJECTION"
        )

        // Allow draw over other apps (SYSTEM_ALERT_WINDOW)
        instrumentation.uiAutomation.executeShellCommand(
            "appops set ${context.packageName} SYSTEM_ALERT_WINDOW allow"
        )

        instrumentation.uiAutomation.executeShellCommand(
            "appops set ${context.packageName} PROJECT_MEDIA allow"
        )
    }

    @Test   //Test generated by AI, Initial version failed had AI generate version that could build and run
    fun testServiceStartsSuccessfully() {
        val context = ApplicationProvider.getApplicationContext<Context>()
        val startIntent = Intent(context, ScreenMonitoringService::class.java).apply {
            putExtra("resultCode", -1)
        }

        context.startService(startIntent)

        // Wait up to 2 seconds for service onCreate and channel creation
        val notificationManager = context.getSystemService(NotificationManager::class.java)
        var channel = notificationManager.getNotificationChannel("monitoring_channel")
        val startTime = System.currentTimeMillis()
        while (channel == null && System.currentTimeMillis() - startTime < 2000) {
            Thread.sleep(100)
            channel = notificationManager.getNotificationChannel("monitoring_channel")
        }

        assertNotNull(channel)
        assertEquals("PhobiaGuard Monitoring", channel?.name)
    }
}
